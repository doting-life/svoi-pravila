import { describe, expect, it } from "vitest";

import { decodeRemainingLabel } from "./plural";

describe("decodeRemainingLabel", () => {
    it.each([
        [0, "Сегодня осталось 0 разборов"],
        [1, "Сегодня остался 1 разбор"],
        [2, "Сегодня осталось 2 разбора"],
        [4, "Сегодня осталось 4 разбора"],
        [5, "Сегодня осталось 5 разборов"],
        [11, "Сегодня осталось 11 разборов"],
        [12, "Сегодня осталось 12 разборов"],
        [14, "Сегодня осталось 14 разборов"],
        [21, "Сегодня остался 21 разбор"],
        [22, "Сегодня осталось 22 разбора"],
        [37, "Сегодня осталось 37 разборов"],
        [111, "Сегодня осталось 111 разборов"],
    ])("formats %i", (count, expected) => {
        expect(decodeRemainingLabel(count)).toBe(expected);
    });
});
